-- Esquema do catálogo no PostgreSQL. Roda a cada início: tudo é "se não existir".
-- Datas ficam como texto 'AAAA-MM-DD HH:MM:SS' em UTC, o formato que o sistema já usava (e que ordena certo como texto).

-- Funções de data no estilo do SQLite: sqlite_datetime('now'), sqlite_date(coluna, 'localtime', '+7 days')...
-- Modificadores aceitos: 'localtime', 'utc', 'start of day', 'start of month' e '+N'/'-N' com days, hours, minutes, seconds, months, years.
-- O fuso de 'localtime' vem de app.tz (definido na conexão); sem ele, São Paulo.
CREATE OR REPLACE FUNCTION sqlite_ts(t text, mods text[]) RETURNS timestamp
LANGUAGE plpgsql STABLE AS $$
DECLARE
  ts timestamp;
  m text;
  tz text := COALESCE(NULLIF(current_setting('app.tz', true), ''), 'America/Sao_Paulo');
BEGIN
  IF t IS NULL THEN RETURN NULL; END IF;
  IF lower(t) = 'now' THEN ts := now() AT TIME ZONE 'UTC'; ELSE ts := replace(replace(t, 'T', ' '), 'Z', '')::timestamp; END IF;
  FOREACH m IN ARRAY COALESCE(mods, '{}') LOOP
    m := lower(trim(m));
    IF m = 'localtime' THEN ts := (ts AT TIME ZONE 'UTC') AT TIME ZONE tz;
    ELSIF m = 'utc' THEN ts := (ts AT TIME ZONE tz) AT TIME ZONE 'UTC';
    ELSIF m = 'start of day' THEN ts := date_trunc('day', ts);
    ELSIF m = 'start of month' THEN ts := date_trunc('month', ts);
    ELSIF m ~ '^[+-]?\d+(\.\d+)? (day|hour|minute|second|month|year)s?$' THEN ts := ts + m::interval;
    ELSE RAISE EXCEPTION 'modificador de data não suportado: %', m;
    END IF;
  END LOOP;
  RETURN ts;
END $$;

CREATE OR REPLACE FUNCTION sqlite_datetime(t text, VARIADIC mods text[] DEFAULT '{}') RETURNS text
LANGUAGE sql STABLE AS $$ SELECT to_char(sqlite_ts(t, mods), 'YYYY-MM-DD HH24:MI:SS') $$;

CREATE OR REPLACE FUNCTION sqlite_date(t text, VARIADIC mods text[] DEFAULT '{}') RETURNS text
LANGUAGE sql STABLE AS $$ SELECT to_char(sqlite_ts(t, mods), 'YYYY-MM-DD') $$;

